#!/usr/bin/env python3
"""Regenerate the HuggingFace `for-all-dev/ablation-eval` easy/hard splits from `artifacts/`.

`artifacts/lean-ablate/` (mode `corollary-leaves`) -> `easy.jsonl`
`artifacts/lean-ablate-whole/` (mode `corollary-whole`) -> `hard.jsonl`

Each split is the concatenation of every repo's `challenges.jsonl` for that mode, one JSON
object per line, with the repo's `manifest.json` embedded verbatim under a `"manifest"` key
appended to each row (this is the same manifest-embedding convention the 2026-07-27 HF
snapshot uses — there is no separate top-level "mode" field; the split name (easy/hard) *is*
the mode tag, and `manifest.ablator` / `manifest.ablator_flags` carry the
`corollary-delete-lemmas[-leaves]-all` distinction).

Per-repo `challenges.jsonl` blobs are NOT vendored in git (see `artifacts/MANIFEST_SCHEMA.md`)
so this script pulls each one from the DigitalOcean Space object store
(`s3://forall-ablations/lean/...`, the same tree `pipeline/upload_ablations.sh` publishes to)
unless a matching file is already sitting under `artifacts/`. Every blob — local or freshly
downloaded — is sha256-verified against `artifacts/lean-ablate-whole/_index.json` (the
manifest-derived index regenerated by `pipeline/write_index.py`) before it is allowed into a
split. Any mismatch (missing repo, wrong sha256, wrong byte count) aborts the whole build with
a nonzero exit and NOTHING is written — there is no partial/best-effort split file.

Credentials for the DO Space (`BUCKET_ACCESS_KEY` / `BUCKET_SECRET_KEY`) come from the
environment only, same as `pipeline/upload_ablations.sh` — never hardcoded here.

Usage
-----
    python3 pipeline/build_hf_splits.py build --scratch <dir> [--cache <dir>]
        Verify + assemble <dir>/easy.jsonl and <dir>/hard.jsonl. --cache reuses a directory
        of already-downloaded per-repo blobs across runs (defaults to <dir>/_blobs).

    python3 pipeline/build_hf_splits.py drift-check --scratch <dir> [--repo-id ID]
        Compare a build's easy.jsonl/hard.jsonl (row count + sha256) against the row counts
        HuggingFace's datasets-server reports for the live dataset, and the file sha256 the
        Hub API reports (LFS objects are content-addressed by sha256, so this needs no
        download). Pure read: no credentials required. Exits nonzero if it finds drift.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INDEX_PATH = ROOT / "artifacts/lean-ablate-whole/_index.json"
DO_BUCKET_HOST = "nyc3.digitaloceanspaces.com"
DO_SPACE = "s3://forall-ablations/lean"

# index mode key -> (local artifact tree, DO Space prefix, split filename)
MODES = {
    "corollary-leaves": ("artifacts/lean-ablate", "corollary-leaves", "easy.jsonl"),
    "corollary-whole": ("artifacts/lean-ablate-whole", "corollary-whole", "hard.jsonl"),
}


def sha256_file(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def load_index() -> dict:
    if not INDEX_PATH.exists():
        sys.exit(
            f"refusing to build: index not found at {INDEX_PATH} (run pipeline/write_index.py)"
        )
    return json.loads(INDEX_PATH.read_text())


def s3cmd_config() -> str:
    """Write a throwaway s3cmd config from env creds, mirroring upload_ablations.sh."""
    access = os.environ.get("BUCKET_ACCESS_KEY")
    secret = os.environ.get("BUCKET_SECRET_KEY")
    if not access or not secret:
        sys.exit(
            "refusing to fetch source blobs: set BUCKET_ACCESS_KEY and BUCKET_SECRET_KEY "
            "(same credentials pipeline/upload_ablations.sh uses) — never hardcoded here."
        )
    fd, path = tempfile.mkstemp(prefix="hf-splits-s3cfg-")
    os.close(fd)
    os.chmod(path, 0o600)
    Path(path).write_text(
        "[default]\n"
        f"access_key = {access}\n"
        f"secret_key = {secret}\n"
        f"host_base = {DO_BUCKET_HOST}\n"
        f"host_bucket = %(bucket)s.{DO_BUCKET_HOST}\n"
        "use_https = True\n"
    )
    return path


def fetch_blob(repo: str, do_prefix: str, dest: Path, cfg_path: str) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    url = f"{DO_SPACE}/{do_prefix}/{repo}/challenges.jsonl"
    print(f"  fetching {url} -> {dest}", file=sys.stderr)
    subprocess.run(
        ["s3cmd", "-c", cfg_path, "--no-progress", "get", "--force", url, str(dest)],
        check=True,
    )


def resolve_blob(
    repo: str,
    tree: str,
    do_prefix: str,
    expect: dict,
    cache_dir: Path,
    cfg_path_holder: list,
) -> Path:
    """Return a local path to repo's challenges.jsonl, verified against `expect` (sha256/bytes)."""
    local = ROOT / tree / repo / "challenges.jsonl"
    if local.exists() and local.stat().st_size == expect["bytes"]:
        if sha256_file(local) == expect["sha256"]:
            return local
        print(
            f"  WARNING: {local} present but sha256 mismatch, will refetch from DO Space",
            file=sys.stderr,
        )

    cached = cache_dir / do_prefix / repo / "challenges.jsonl"
    if not (
        cached.exists()
        and cached.stat().st_size == expect["bytes"]
        and sha256_file(cached) == expect["sha256"]
    ):
        if not cfg_path_holder:
            cfg_path_holder.append(s3cmd_config())
        fetch_blob(repo, do_prefix, cached, cfg_path_holder[0])

    got_bytes = cached.stat().st_size
    got_sha = sha256_file(cached)
    if got_bytes != expect["bytes"] or got_sha != expect["sha256"]:
        raise SystemExit(
            f"refusing to publish: {repo}/{do_prefix}/challenges.jsonl does not match "
            f"_index.json — expected {expect['bytes']} bytes / sha256 {expect['sha256']}, "
            f"got {got_bytes} bytes / sha256 {got_sha}"
        )
    return cached


def cmd_build(args: argparse.Namespace) -> None:
    idx = load_index()
    scratch = Path(args.scratch)
    scratch.mkdir(parents=True, exist_ok=True)
    cache_dir = Path(args.cache) if args.cache else scratch / "_blobs"
    cfg_path_holder: list[str] = []

    summary = {}
    try:
        for mode_key, (tree, do_prefix, split_name) in MODES.items():
            out_path = scratch / (split_name + ".partial")
            n_rows = 0
            with open(out_path, "w") as out:
                for repo in sorted(idx["repos"]):
                    if args.repos and repo not in args.repos:
                        continue
                    entry = idx["repos"][repo]
                    modes = entry.get("modes", {})
                    if mode_key not in modes:
                        continue
                    blobs = modes[mode_key].get("blobs", {})
                    expect = blobs.get("challenges.jsonl")
                    if not expect:
                        continue  # repo mined but nothing survived validation for this mode
                    manifest_path = ROOT / tree / repo / "manifest.json"
                    if not manifest_path.exists():
                        raise SystemExit(
                            f"refusing to publish: missing {manifest_path}"
                        )
                    manifest = json.loads(manifest_path.read_text())

                    blob_path = resolve_blob(
                        repo, tree, do_prefix, expect, cache_dir, cfg_path_holder
                    )
                    with open(blob_path) as f:
                        for line in f:
                            line = line.strip()
                            if not line:
                                continue
                            row = json.loads(line)
                            row["manifest"] = manifest
                            out.write(json.dumps(row) + "\n")
                            n_rows += 1

            final_path = scratch / split_name
            os.replace(out_path, final_path)
            if args.repos:
                expected_total = sum(
                    idx["repos"][r]["modes"][mode_key]["validated"]
                    for r in args.repos
                    if mode_key in idx["repos"].get(r, {}).get("modes", {})
                )
            else:
                expected_total = (
                    idx.get("totals", {}).get(mode_key, {}).get("validated", 0)
                )
            if n_rows != expected_total:
                raise SystemExit(
                    f"refusing to publish: {split_name} has {n_rows} rows, "
                    f"expected {expected_total} from _index.json"
                )
            digest = sha256_file(final_path)
            summary[split_name] = {
                "rows": n_rows,
                "sha256": digest,
                "bytes": final_path.stat().st_size,
            }
            print(
                f"{split_name}: {n_rows} rows, sha256={digest}, {final_path.stat().st_size} bytes"
            )
    finally:
        if cfg_path_holder:
            try:
                os.unlink(cfg_path_holder[0])
            except OSError:
                pass

    (scratch / "_build_manifest.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(
        f"OK: verified against {INDEX_PATH} — wrote {scratch}/easy.jsonl and {scratch}/hard.jsonl"
    )


def hf_json(url: str) -> dict:
    with urllib.request.urlopen(url, timeout=60) as resp:
        return json.loads(resp.read())


def cmd_drift_check(args: argparse.Namespace) -> None:
    scratch = Path(args.scratch)
    build_manifest_path = scratch / "_build_manifest.json"
    if not build_manifest_path.exists():
        sys.exit(f"run `build --scratch {scratch}` first (no {build_manifest_path})")
    local = json.loads(build_manifest_path.read_text())

    repo_id = args.repo_id
    print(f"comparing local build in {scratch} against live {repo_id}\n")

    size_info = hf_json(
        f"https://datasets-server.huggingface.co/size?dataset={repo_id}"
    )
    remote_rows = {s["split"]: s["num_rows"] for s in size_info["size"]["splits"]}

    tree_info = hf_json(
        f"https://huggingface.co/api/datasets/{repo_id}/tree/main/ablation-eval?expand=true"
    )
    remote_sha = {}
    for entry in tree_info:
        name = Path(entry["path"]).name
        remote_sha[name] = entry.get("lfs", {}).get("oid") or entry.get("oid")

    drift = False
    for split_name, local_info in local.items():
        remote_row_count = remote_rows.get(split_name.removesuffix(".jsonl"))
        remote_sha256 = remote_sha.get(split_name)
        row_match = remote_row_count == local_info["rows"]
        sha_match = remote_sha256 == local_info["sha256"]
        status = "MATCH" if (row_match and sha_match) else "DRIFT"
        if status == "DRIFT":
            drift = True
        print(f"[{status}] {split_name}")
        print(
            f"    rows:   local={local_info['rows']}  hf={remote_row_count}  {'OK' if row_match else 'MISMATCH'}"
        )
        print(f"    sha256: local={local_info['sha256']}")
        print(f"            hf   ={remote_sha256}  {'OK' if sha_match else 'MISMATCH'}")

    if drift:
        print(
            "\nDRIFT DETECTED: the live HF dataset does not match a from-source rebuild."
        )
        sys.exit(1)
    print("\nNo drift: live HF dataset matches a from-source rebuild.")


def main() -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    sub = ap.add_subparsers(dest="cmd", required=True)

    b = sub.add_parser("build", help="assemble + verify easy.jsonl / hard.jsonl")
    b.add_argument("--scratch", required=True, help="output directory")
    b.add_argument(
        "--cache",
        help="directory to cache downloaded per-repo blobs (default: <scratch>/_blobs)",
    )
    b.add_argument(
        "--repos",
        nargs="+",
        help="only include these repos (testing / partial builds — full builds must omit this "
        "so the row-count check covers the whole corpus)",
    )
    b.set_defaults(func=cmd_build)

    d = sub.add_parser(
        "drift-check", help="compare a build against the live HF dataset"
    )
    d.add_argument(
        "--scratch", required=True, help="directory containing a prior `build`"
    )
    d.add_argument("--repo-id", default="for-all-dev/ablation-eval")
    d.set_defaults(func=cmd_drift_check)

    args = ap.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
